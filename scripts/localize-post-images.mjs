#!/usr/bin/env node
// Copies the Medium-hosted images used in posts into public/ and writes lib/post-images.ts.
// Post markdown stays unchanged; lib/posts.ts swaps the URLs when rendering.
import { createHash } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const OUT = "public/images/blog/body";
const MAX_WIDTH = 1400;

const urls = new Set(
  fs
    .readdirSync("content/blog")
    .flatMap((f) => [...fs.readFileSync(path.join("content/blog", f), "utf8").matchAll(/!\[[^\]]*\]\((https:\/\/miro\.medium\.com[^)\s]+)/g)])
    .map((m) => m[1]),
);

fs.mkdirSync(OUT, { recursive: true });
const entries = [];
for (const url of [...urls].sort()) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} for ${url}`);
  const name = `${createHash("sha1").update(url).digest("hex").slice(0, 12)}.webp`;
  const info = await sharp(Buffer.from(await res.arrayBuffer()))
    .resize({ width: MAX_WIDTH, withoutEnlargement: true })
    .webp({ quality: 80 })
    .toFile(path.join(OUT, name));
  entries.push([url, { src: `/images/blog/body/${name}`, width: info.width, height: info.height }]);
}

const body = entries.map(([url, v]) => `  ${JSON.stringify(url)}: ${JSON.stringify(v)},`).join("\n");
fs.writeFileSync(
  "lib/post-images.ts",
  `// Generated by scripts/localize-post-images.mjs. Do not edit.\nexport const POST_IMAGES: Record<string, { src: string; width: number; height: number }> = {\n${body}\n};\n`,
);
console.log(`${entries.length} images`);
